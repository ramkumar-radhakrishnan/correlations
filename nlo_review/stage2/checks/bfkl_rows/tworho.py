N0=1/(2*np.pi)**3/(16*np.pi**5)
def hc(op):
    return {k[::-1]:np.conj(np.transpose(v)) if np.ndim(v) else np.conj(v) for k,v in op.items()}
def ev(env,texts,cc=False,herm_only=False):
    """operator of sum of texts (+ h.c. with w<->w' if cc)"""
    tot={}
    for t in texts: tot=add(tot,evaluate(env,t))
    if cc or herm_only:
        X=env["X"]; X["w"],X["w'"]=X["w'"],X["w"]
        c={}
        for t in texts: c=add(c,evaluate(env,t))
        X["w"],X["w'"]=X["w'"],X["w"]
        tot=hc(c) if (herm_only or cc=="h") else add(tot,hc(c))
    return tot
def F(env,texts,p,q,cc=False,mode="sym",eps=0.0,rng=None,odd_only=None):
    """two-rho coefficient F^{de}(p,q) rho^d(p) rho^e(q) obtained from the operator:
       direct 2-rho terms + 2-rho terms generated by putting 3-rho products into the reference ordering 'mode'"""
    X=env["X"]; save={k:X[k].copy() for k in ("x","x'","y")}
    f=env["f"]; n=env["n"]; out=np.zeros((n,n),complex)
    X["x'"]=p.copy(); X["x"]=q.copy()
    op=ev(env,texts,cc)
    for k,v in op.items():
        if len(k)==2:
            assert set(k)=={"x","x'"},k
            out+= v if k==("x'","x") else v.T
    if any(len(k)==3 for k in op):
        for odd in (("x","x'","y") if odd_only is None else (odd_only,)):
            pair=[a for a in ("x","x'","y") if a!=odd]
            X[odd]=q.copy(); X[pair[0]]=p.copy(); X[pair[1]]=p.copy()+(eps*np.array([0.6,-0.8]) if eps else 0)
            op=ev(env,texts,cc)
            for k,v in op.items():
                if len(k)!=3: continue
                assert set(k)=={"x","x'","y"},k
                io=k.index(odd); i,j=[m for m in range(3) if m!=io]   # i<j : written order of the coinciding pair
                # X_i X_j X_o-type product; symmetric ordering: (1/2) [X_i,X_j] o X_odd
                w=np.moveaxis(v,[i,j,io],[0,1,2])
                if mode=="sym": out+=0.5*1j*np.einsum("abd,abe->de",f,w)
                else: raise ValueError
    for k in save: X[k]=save[k]
    return out
def Finv(env,texts,u,v,**kw):
    return (F(env,texts,u,v,**kw)+F(env,texts,v,u,**kw).T)/N0
